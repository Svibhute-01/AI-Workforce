import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import { CheckCircle, ChevronLeft, ChevronRight, CircleDashed, Clock, ListChecks, RefreshCw, Search, Sparkles } from 'lucide-react'
import StatusBadge from '../components/common/StatusBadge'
import { EmptyState, ErrorState, Notice, PageHeader, Skeleton } from '../components/common/States'
import apiService from '../services/api'
import { fmtDate, humanize } from '../utils/format'
import { PRIORITY_ORDER, STATUS_ORDER, countBy, filterTasks, flattenTasks, paginate } from '../utils/taskModel'

const PAGE_SIZE = 10
const PRIORITY_BADGE = { HIGH: 'badge-danger', MEDIUM: 'badge-warning', LOW: 'badge-success' }
const STATUS_LABEL = { TODO: 'To do', IN_PROGRESS: 'In progress', COMPLETED: 'Completed' }

function Tasks() {
  const [rows, setRows] = useState([])
  const [loading, setLoading] = useState(true)
  const [refreshing, setRefreshing] = useState(false)
  const [error, setError] = useState('')
  const [skipped, setSkipped] = useState(0)
  const [projectCount, setProjectCount] = useState(0)
  const [search, setSearch] = useState('')
  const [project, setProject] = useState('all')
  const [status, setStatus] = useState('all')
  const [priority, setPriority] = useState('all')
  const [page, setPage] = useState(1)
  const alive = useRef(true)

  const load = useCallback(async (isRefresh = false) => {
    if (isRefresh) setRefreshing(true)
    else setLoading(true)
    try {
      const projects = await apiService.projects.getAll()
      const settled = await Promise.allSettled(projects.map((item) => apiService.projectManager.get(item.id)))
      if (!alive.current) return
      if (projects.length && settled.every((result) => result.status === 'rejected')) {
        const firstReason = settled[0].reason
        const noPlansYet = settled.every((result) => /404|not (found|generated)/i.test(result.reason?.message || ''))
        if (!noPlansYet) throw firstReason
      }
      const plans = settled.map((result) => (result.status === 'fulfilled' ? result.value : null))
      setRows(flattenTasks(projects, plans))
      setProjectCount(projects.length)
      setSkipped(settled.filter((result) => result.status === 'rejected' && !/404|not (found|generated)/i.test(result.reason?.message || '')).length)
      setError('')
    } catch (requestError) {
      if (alive.current) setError(requestError.message || 'Could not load tasks.')
    } finally {
      if (alive.current) {
        setLoading(false)
        setRefreshing(false)
      }
    }
  }, [])

  useEffect(() => {
    alive.current = true
    load()
    return () => { alive.current = false }
  }, [load])

  useEffect(() => { setPage(1) }, [search, project, status, priority])

  const projectOptions = useMemo(() => {
    const seen = new Map()
    rows.forEach((row) => seen.set(row.projectId, row.project))
    return [...seen.entries()]
  }, [rows])

  const filtered = useMemo(() => filterTasks(rows, { search, project, status, priority }), [rows, search, project, status, priority])
  const view = useMemo(() => paginate(filtered, page, PAGE_SIZE), [filtered, page])
  const byStatus = useMemo(() => countBy(rows, 'status'), [rows])
  const filtersActive = search || project !== 'all' || status !== 'all' || priority !== 'all'

  const chips = [
    { key: 'all', label: 'All tasks', count: rows.length, icon: ListChecks },
    { key: 'TODO', label: 'To do', count: byStatus.TODO || 0, icon: CircleDashed },
    { key: 'IN_PROGRESS', label: 'In progress', count: byStatus.IN_PROGRESS || 0, icon: Clock },
    { key: 'COMPLETED', label: 'Completed', count: byStatus.COMPLETED || 0, icon: CheckCircle },
  ]

  return (
    <div>
      <PageHeader
        title="Tasks"
        subtitle="Every task generated by the Project Manager AI across your projects"
        actions={(
          <>
            <button type="button" onClick={() => load(true)} disabled={loading || refreshing} className="btn-outline flex items-center gap-2">
              <RefreshCw className={`h-4 w-4 ${refreshing ? 'animate-spin' : ''}`} /> Refresh
            </button>
            <Link to="/agents" className="btn-primary flex items-center gap-2"><Sparkles className="h-4 w-4" /> Plan with AI</Link>
          </>
        )}
      />

      {error && rows.length > 0 && <Notice tone="error" onRetry={() => load(true)}>Refresh failed: {error}</Notice>}
      {skipped > 0 && <Notice tone="warning">Plans for {skipped} project{skipped === 1 ? '' : 's'} could not be loaded, so their tasks are missing here.</Notice>}

      {loading && !rows.length ? (
        <div className="space-y-4" aria-busy="true" aria-label="Loading tasks">
          <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">{[0, 1, 2, 3].map((i) => <Skeleton key={i} className="h-20" />)}</div>
          <Skeleton className="h-20" />
          <Skeleton className="h-96" />
        </div>
      ) : error && !rows.length ? (
        <ErrorState title="Couldn't load tasks" message={error} onRetry={() => load()} retrying={loading} />
      ) : projectCount === 0 ? (
        <EmptyState icon={ListChecks} title="No projects yet" hint="Create a project, upload an SRS and generate a plan to see tasks here." to="/projects" cta="Create a project" />
      ) : rows.length === 0 ? (
        <EmptyState icon={ListChecks} title="No tasks have been planned yet" hint="Run the Requirements Analyst, then the Project Manager AI. Its tasks will be listed here." to="/agents" cta="Open AI Agents" />
      ) : (
        <>
          <div className="bt-stagger mb-6 grid grid-cols-2 gap-4 lg:grid-cols-4">
            {chips.map((chip) => {
              const Icon = chip.icon
              const active = status === chip.key
              return (
                <button
                  key={chip.key}
                  type="button"
                  aria-pressed={active}
                  onClick={() => setStatus(chip.key)}
                  className={`card lift group flex items-center gap-3 p-4 text-left ${active ? 'ring-2 ring-brand-deep' : ''}`}
                >
                  <span className="bt-icon-bubble h-10 w-10 shrink-0"><Icon className="h-5 w-5" /></span>
                  <span>
                    <span className="block text-2xl font-extrabold tabular-nums text-text-primary">{chip.count}</span>
                    <span className="block text-xs font-bold uppercase tracking-wide text-text-secondary">{chip.label}</span>
                  </span>
                </button>
              )
            })}
          </div>

          <div className="card mb-6 p-5">
            <div className="flex flex-col gap-4 md:flex-row">
              <div className="relative flex-1">
                <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-text-secondary" />
                <input type="search" aria-label="Search tasks" placeholder="Search tasks, roles, sprints..." value={search} onChange={(e) => setSearch(e.target.value)} className="input-field w-full pl-10" />
              </div>
              <select aria-label="Filter by project" value={project} onChange={(e) => setProject(e.target.value)} className="input-field">
                <option value="all">All projects</option>
                {projectOptions.map(([id, name]) => <option key={id} value={id}>{name}</option>)}
              </select>
              <select aria-label="Filter by status" value={status} onChange={(e) => setStatus(e.target.value)} className="input-field">
                <option value="all">All statuses</option>
                {STATUS_ORDER.map((key) => <option key={key} value={key}>{STATUS_LABEL[key]}</option>)}
              </select>
              <select aria-label="Filter by priority" value={priority} onChange={(e) => setPriority(e.target.value)} className="input-field">
                <option value="all">All priorities</option>
                {PRIORITY_ORDER.map((key) => <option key={key} value={key}>{humanize(key)}</option>)}
              </select>
            </div>
          </div>

          <div className="card overflow-hidden">
            <div className="overflow-x-auto">
              <table className="w-full min-w-[820px]">
                <thead>
                  <tr className="table-header">
                    <th className="px-6 py-3 text-left">Task</th>
                    <th className="px-6 py-3 text-left">Project</th>
                    <th className="px-6 py-3 text-left">Suggested role</th>
                    <th className="px-6 py-3 text-left">Priority</th>
                    <th className="px-6 py-3 text-left">Points</th>
                    <th className="px-6 py-3 text-left">Sprint</th>
                    <th className="px-6 py-3 text-left">Status</th>
                  </tr>
                </thead>
                <tbody>
                  {view.items.map((task) => (
                    <tr key={task.key} className="border-b border-border-light last:border-b-0">
                      <td className="max-w-xs px-6 py-4">
                        <p className="font-bold text-text-primary">{task.title}</p>
                        {task.taskId && <p className="text-xs text-text-secondary">{task.taskId}</p>}
                      </td>
                      <td className="px-6 py-4 text-sm"><Link to={`/projects/${task.projectId}`} className="font-semibold text-primary hover:underline">{task.project}</Link></td>
                      <td className="px-6 py-4 text-sm text-text-primary">{task.role ? humanize(task.role) : '—'}</td>
                      <td className="px-6 py-4">{task.priority ? <span className={`badge ${PRIORITY_BADGE[task.priority] || 'bg-gray-100 text-text-secondary'}`}>{humanize(task.priority)}</span> : '—'}</td>
                      <td className="px-6 py-4 text-sm tabular-nums text-text-primary">{task.points ?? '—'}</td>
                      <td className="px-6 py-4 text-sm text-text-secondary">{task.sprint || '—'}{task.sprintEnd && <span className="block text-xs">ends {fmtDate(task.sprintEnd)}</span>}</td>
                      <td className="px-6 py-4"><StatusBadge status={task.status} /></td>
                    </tr>
                  ))}
                </tbody>
              </table>
              {!view.items.length && (
                <p className="p-8 text-center text-text-secondary">
                  {filtersActive ? 'No tasks match your filters.' : 'No tasks to show.'}
                </p>
              )}
            </div>

            <div className="flex flex-col items-center justify-between gap-3 border-t border-border-light p-5 sm:flex-row">
              <p className="text-sm text-text-secondary">
                {filtered.length ? `Showing ${view.start} to ${view.end} of ${filtered.length} task${filtered.length === 1 ? '' : 's'}` : 'Showing 0 tasks'}
                {filtered.length !== rows.length && ` (filtered from ${rows.length})`}
              </p>
              <div className="flex items-center gap-2">
                <button type="button" aria-label="Previous page" disabled={view.page <= 1} onClick={() => setPage(view.page - 1)} className="btn-secondary flex items-center px-2.5 py-1.5"><ChevronLeft className="h-4 w-4" /></button>
                <span className="px-2 text-sm font-bold tabular-nums text-text-primary">Page {view.page} of {view.pages}</span>
                <button type="button" aria-label="Next page" disabled={view.page >= view.pages} onClick={() => setPage(view.page + 1)} className="btn-secondary flex items-center px-2.5 py-1.5"><ChevronRight className="h-4 w-4" /></button>
              </div>
            </div>
          </div>
        </>
      )}
    </div>
  )
}

export default Tasks
